import AppKit
import Domain

/// `PasteboardAccessing` for the general pasteboard. Every item's every type
/// is copied as raw data, which covers plain text, rich text, images, and
/// file URLs. Contents are never logged.
public struct SystemPasteboard: PasteboardAccessing {
    /// Larger clipboards are not snapshotted (the fallback leaves them alone).
    private static let snapshotLimitBytes = 64 * 1_048_576

    /// Markers from nspasteboard.org that tell clipboard managers to skip
    /// LemmeType's temporary value.
    private static let transientTypes = [
        NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"),
    ]

    public init() {}

    public func changeCount() async -> Int {
        await MainActor.run { NSPasteboard.general.changeCount }
    }

    public func snapshot() async -> PasteboardSnapshot {
        await MainActor.run {
            var items: [[String: Data]] = []
            var complete = true
            var total = 0
            for item in NSPasteboard.general.pasteboardItems ?? [] {
                var copy: [String: Data] = [:]
                for type in item.types {
                    // Promised data (for example file promises) can't be read back.
                    guard let data = item.data(forType: type) else {
                        complete = false
                        continue
                    }
                    total += data.count
                    copy[type.rawValue] = data
                }
                items.append(copy)
            }
            if total > Self.snapshotLimitBytes {
                return PasteboardSnapshot(items: [], isComplete: false)
            }
            return PasteboardSnapshot(items: items, isComplete: complete)
        }
    }

    public func writeTransient(_ text: String) async -> Int {
        await MainActor.run {
            let pasteboard = NSPasteboard.general
            pasteboard.clearContents()
            let item = NSPasteboardItem()
            item.setString(text, forType: .string)
            for type in Self.transientTypes {
                item.setData(Data(), forType: type)
            }
            pasteboard.writeObjects([item])
            return pasteboard.changeCount
        }
    }

    public func write(_ text: String) async {
        await MainActor.run {
            NSPasteboard.general.clearContents()
            NSPasteboard.general.setString(text, forType: .string)
        }
    }

    public func restore(_ snapshot: PasteboardSnapshot) async {
        await MainActor.run {
            let pasteboard = NSPasteboard.general
            pasteboard.clearContents()
            let items = snapshot.items.map { types in
                let item = NSPasteboardItem()
                for (type, data) in types {
                    item.setData(data, forType: NSPasteboard.PasteboardType(type))
                }
                return item
            }
            if !items.isEmpty {
                pasteboard.writeObjects(items)
            }
        }
    }
}
